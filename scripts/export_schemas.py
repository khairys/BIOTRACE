"""F1–F42 [MVP]: generate TypeScript directly from pydantic JSON Schema."""

import json
from pathlib import Path

from api.contracts import (
    DatasetsResponse,
    ErrorResponse,
    HealthResponse,
    MethodsResponse,
    ReferenceStats,
    ValidationResults,
)
from biotrace_core.config import ROOT
from biotrace_core.models import RunCreated, RunResult


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(ts_type(s) for s in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        return (
            f"Record<string, {ts_type(schema['additionalProperties'])}>"
            if isinstance(schema.get("additionalProperties"), dict)
            else "Record<string, unknown>"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate(destination: Path = ROOT / "web/src/api/generated.ts") -> str:
    schemas = [
        model.model_json_schema()
        for model in (
            RunResult,
            RunCreated,
            HealthResponse,
            ReferenceStats,
            MethodsResponse,
            ValidationResults,
            DatasetsResponse,
            ErrorResponse,
        )
    ]
    definitions = {}
    for schema in schemas:
        definitions.update(schema.get("$defs", {}))
        definitions[schema["title"]] = schema
    output = ["// Generated by scripts/export_schemas.py from pydantic. DO NOT EDIT."]
    for name, schema in sorted(definitions.items()):
        if "properties" not in schema:
            output.append(f"export type {name} = {ts_type(schema)};")
            continue
        output.append(f"export interface {name} {{")
        # Output models include defaults: FastAPI serializes all fields.
        for field, value in schema["properties"].items():
            output.append(f"  {field}: {ts_type(value)};")
        output.append("}")
    value = "\n".join(output) + "\n"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(value, encoding="utf-8", newline="\n")
    (destination.parent / "schema.json").write_text(
        json.dumps(schemas[0], sort_keys=True, indent=2) + "\n", encoding="utf-8"
    )
    return value


if __name__ == "__main__":
    generate()
